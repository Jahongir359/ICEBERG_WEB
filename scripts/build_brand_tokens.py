"""Generate static/brand/tokens.css from static/brand/tokens.json.

tokens.json is a copy of College-ERP/docs/brand/iceberg-school/tokens.json (the
source of truth). Run this after copying a new version; check_firebase_build.py
fails when the CSS is out of date.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS_JSON = ROOT / 'static' / 'brand' / 'tokens.json'
TOKENS_CSS = ROOT / 'static' / 'brand' / 'tokens.css'

# Colours that page CSS also needs as "R G B" channels for rgb(... / alpha).
RGB_CHANNELS = ('primary', 'primaryHover', 'primaryDeep', 'onPrimarySoft', 'accent', 'bg', 'text', 'gold', 'cream')


def kebab(name):
    return re.sub(r'(?<!^)(?=[A-Z0-9])', '-', name).lower()


def channels(hex_value):
    value = hex_value.lstrip('#')
    return ' '.join(str(int(value[index:index + 2], 16)) for index in (0, 2, 4))


def brand_block(selector, colours):
    lines = [f'{selector} {{']
    for name, value in colours.items():
        lines.append(f'    --brand-{kebab(name)}: {value};')
    for name in RGB_CHANNELS:
        if name in colours:
            lines.append(f'    --brand-{kebab(name)}-rgb: {channels(colours[name])};')
    lines.append('}')
    return '\n'.join(lines)


def render(tokens):
    shared = [':root {', f"    --brand-font: '{tokens['font']['family']}', system-ui, -apple-system, 'Segoe UI', sans-serif;"]
    display = tokens['font'].get('display')
    if display:
        shared.append(f"    --brand-font-display: '{display['family']}', Georgia, 'Times New Roman', serif;")
    for name, value in tokens['radius'].items():
        shared.append(f'    --brand-radius-{kebab(name)}: {value}px;')
    for name, value in tokens['semantic'].items():
        shared.append(f'    --brand-{name}: {value};')
    shared.append('}')

    blocks = [
        '/* Generated by scripts/build_brand_tokens.py from tokens.json. Do not edit. */',
        '\n'.join(shared),
    ]
    center = tokens['brands']['center']['light']
    blocks.append(brand_block(':root,\nhtml[data-brand="center"]', center))
    for key, brand in tokens['brands'].items():
        if key == 'center':
            continue
        blocks.append(brand_block(f'html[data-brand="{key}"]', brand['light']))
    return '\n\n'.join(blocks) + '\n'


def main():
    tokens = json.loads(TOKENS_JSON.read_text(encoding='utf-8'))
    css = render(tokens)
    if '--check' in sys.argv:
        current = TOKENS_CSS.read_text(encoding='utf-8') if TOKENS_CSS.exists() else ''
        if current != css:
            print('static/brand/tokens.css is out of date; run scripts/build_brand_tokens.py')
            return 1
        return 0
    TOKENS_CSS.write_text(css, encoding='utf-8')
    print(f'Wrote {TOKENS_CSS.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
